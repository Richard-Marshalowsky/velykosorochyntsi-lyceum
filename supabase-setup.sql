create extension if not exists http with schema extensions;

-- 1. ADMIN USERS TABLE
create table if not exists public.admin_users (
  email text primary key check (email = lower(email)),
  role text not null check (role in ('editor','admin','super_admin')),
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;

-- 2. SITE CONTENT (Editable text)
create table if not exists public.site_content (
  key text primary key,
  page text not null,
  value text not null,
  updated_by text not null,
  updated_at timestamptz not null default now()
);
alter table public.site_content enable row level security;

-- 3. NEWS TABLE
create table if not exists public.news (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'general' check (category in ('general', 'important', 'it', 'sport')),
  body text not null,
  author_email text not null,
  created_at timestamptz not null default now()
);
alter table public.news enable row level security;

-- 4. DOCUMENTS TABLE
create table if not exists public.documents (
  id bigint generated by default as identity primary key,
  title text not null,
  type text not null default 'normative',
  url text not null,
  author_email text not null,
  created_at timestamptz not null default now()
);
alter table public.documents enable row level security;

-- 5. SCHEDULE TABLE
create table if not exists public.schedule (
  class text primary key,
  lessons jsonb not null default '{}'::jsonb,
  updated_by text not null,
  updated_at timestamptz not null default now()
);
alter table public.schedule enable row level security;

-- 6. TRUST MESSAGES (Скринька довіри)
create table if not exists public.trust_messages (
  id bigint generated by default as identity primary key,
  name text not null default 'Анонімно',
  status text not null default 'other',
  subject text not null,
  message text not null,
  created_at timestamptz not null default now()
);
alter table public.trust_messages enable row level security;

-- 7. COMMENTS & REVIEWS TABLE
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  page text not null default '/index.html',
  author_name text not null default 'Гість',
  author_email text,
  content text not null,
  created_at timestamptz not null default now()
);
alter table public.comments enable row level security;

-- 8. RATE LIMIT TABLES
create table if not exists public.trust_rate_limits (
  ip_address text primary key,
  last_submitted_at timestamptz not null default now()
);
alter table public.trust_rate_limits enable row level security;
revoke all on public.trust_rate_limits from anon, authenticated;

create table if not exists public.comment_rate_limits (
  ip_address text primary key,
  last_submitted_at timestamptz not null default now()
);
alter table public.comment_rate_limits enable row level security;
revoke all on public.comment_rate_limits from anon, authenticated;


