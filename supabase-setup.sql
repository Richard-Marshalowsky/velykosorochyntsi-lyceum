-- =========================================================================
-- SECURE RPC: SUBMIT TRUST MESSAGE (Strict Fail-Closed, IP Protected)
-- =========================================================================
drop function if exists public.submit_trust_message_secure(text, text, text, text);
drop function if exists public.submit_trust_message_secure(text, text, text, text, text);

create or replace function public.submit_trust_message_secure(
  p_name text,
  p_status text,
  p_subject text,
  p_message text,
  p_turnstile_token text default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_headers jsonb;
  v_client_ip text;
  v_cooldown_seconds int := 60;
  -- Set your real secret key here directly in Supabase SQL editor (never commit real secret to git)
  v_turnstile_secret text := 'YOUR_TURNSTILE_SECRET_KEY';
  v_turnstile_ok boolean := false;
  v_http_response extensions.http_response;
  v_response_body jsonb;
begin
  -- 1. Server-side string length validations
  if p_message is null or trim(p_message) = '' then
    raise exception 'Текст звернення не може бути порожнім';
  end if;
  if length(p_message) > 5000 then
    raise exception 'Текст звернення занадто довгий (максимум 5000 символів)';
  end if;
  if p_subject is null or trim(p_subject) = '' then
    raise exception 'Тема звернення не може бути порожньою';
  end if;
  if length(p_subject) > 200 then
    raise exception 'Тема звернення занадто довга (максимум 200 символів)';
  end if;
  if p_name is not null and length(p_name) > 100 then
    raise exception 'Ім''я занадто довге (максимум 100 символів)';
  end if;
  -- Validate p_status against whitelist
  if p_status is not null and p_status not in ('student', 'parent', 'teacher', 'other', '') then
    raise exception 'Невідомий статус';
  end if;

  -- 2. Turnstile Captcha verification (Strict Fail-Closed)
  if p_turnstile_token is null or trim(p_turnstile_token) = '' then
    raise exception 'Пройдіть перевірку безпеки (капчу)';
  end if;

  if v_turnstile_secret is null or v_turnstile_secret = '' or v_turnstile_secret = 'YOUR_TURNSTILE_SECRET_KEY' then
    raise exception 'Секретний ключ капчі не налаштований на сервері';
  end if;

  begin
    select * into v_http_response from extensions.http_post(
      'https://challenges.cloudflare.com/turnstile/v0/siteverify',
      json_build_object(
        'secret', v_turnstile_secret,
        'response', trim(p_turnstile_token)
      )::text,
      'application/json'
    );
    v_response_body := v_http_response.content::jsonb;
    v_turnstile_ok := coalesce((v_response_body->>'success')::boolean, false);
  exception when others then
    raise exception 'Помилка з''єднання з сервісом перевірки безпеки. Спробуйте пізніше.';
  end;

  if not v_turnstile_ok then
    raise exception 'Перевірка безпеки не пройдена. Оновіть сторінку.';
  end if;

  -- 3. Extract real client IP
  begin
    v_headers := current_setting('request.headers', true)::jsonb;
    v_client_ip := coalesce(
      nullif(trim(v_headers->>'cf-connecting-ip'), ''),
      'unknown'
    );
    if v_client_ip like '%,%' then
      v_client_ip := split_part(v_client_ip, ',', 1);
    end if;
  exception when others then
    v_client_ip := 'unknown';
  end;

  -- 4. Atomic Rate Limit (Race Condition Proof & Fail-Closed)
  insert into public.trust_rate_limits(ip_address, last_submitted_at)
  values (v_client_ip, now())
  on conflict (ip_address) do update
  set last_submitted_at = now()
  where public.trust_rate_limits.last_submitted_at <= (now() - (v_cooldown_seconds || ' seconds')::interval);

  if not found then
    raise exception 'Зачекайте 1 хвилину перед наступною відправкою звернення';
  end if;

  -- 5. Insert trust message
  insert into public.trust_messages(name, status, subject, message)
  values (
    coalesce(nullif(trim(p_name), ''), 'Анонімно'),
    coalesce(nullif(trim(p_status), ''), 'other'),
    trim(p_subject),
    trim(p_message)
  );

  return jsonb_build_object('success', true, 'message', 'Звернення надіслано');
end;
$$;

revoke all on function public.submit_trust_message_secure(text, text, text, text, text) from public;
grant execute on function public.submit_trust_message_secure(text, text, text, text, text) to anon, authenticated;


