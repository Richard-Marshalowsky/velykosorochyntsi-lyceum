create or replace function public.submit_comment_secure(
  p_page text,
  p_author_name text,
  p_content text,
  p_turnstile_token text default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_headers jsonb;
  v_client_ip text;
  v_cooldown_seconds int := 20;
  -- Set your real secret key here directly in Supabase SQL editor (never commit real secret to git)
  v_turnstile_secret text := 'YOUR_TURNSTILE_SECRET_KEY';
  v_turnstile_ok boolean := false;
  v_http_response extensions.http_response;
  v_response_body jsonb;
  v_auth_user_id uuid;
  v_auth_email text;
  v_auth_name text;
begin
  -- 1. Server-side authentication check (STRICT: no anonymous comments)
  v_auth_user_id := auth.uid();
  if v_auth_user_id is null then
    raise exception 'Authentication required';
  end if;

  v_auth_email := lower(coalesce(auth.jwt()->>'email', ''));
  if v_auth_email = '' then
    raise exception 'Недійсний акаунт (відсутній email)';
  end if;

  v_auth_name := coalesce(
    nullif(trim(auth.jwt()->>'name'), ''),
    nullif(trim(auth.jwt()->'user_metadata'->>'full_name'), ''),
    nullif(trim(auth.jwt()->'user_metadata'->>'name'), ''),
    nullif(trim(p_author_name), ''),
    'Користувач'
  );
  if length(v_auth_name) > 100 then
    v_auth_name := substring(v_auth_name from 1 for 100);
  end if;

  -- 2. Length & content checks
  if p_content is null or trim(p_content) = '' then
    raise exception 'Текст відгуку не може бути порожнім';
  end if;
  if length(p_content) > 3000 then
    raise exception 'Текст відгуку занадто довгий (максимум 3000 символів)';
  end if;
  if p_page is not null and length(p_page) > 200 then
    raise exception 'Невалідна сторінка';
  end if;

  -- 3. Turnstile Captcha verification (Strict Fail-Closed)
  if p_turnstile_token is null or trim(p_turnstile_token) = '' then
    raise exception 'Пройдіть перевірку безпеки (капчу)';
  end if;

  if v_turnstile_secret is null or v_turnstile_secret = '' or v_turnstile_secret = 'YOUR_TURNSTILE_SECRET_KEY' then
    raise exception 'Секретний ключ капчі не налаштований на сервері';
  end if;

  begin
    select * into v_http_response from extensions.http_post(
      'https://challenges.cloudflare.com/turnstile/v0/siteverify',
      json_build_object(
        'secret', v_turnstile_secret,
        'response', trim(p_turnstile_token)
      )::text,
      'application/json'
    );
    v_response_body := v_http_response.content::jsonb;
    v_turnstile_ok := coalesce((v_response_body->>'success')::boolean, false);
  exception when others then
    raise exception 'Помилка з''єднання з сервісом перевірки безпеки. Спробуйте пізніше.';
  end;

  if not v_turnstile_ok then
    raise exception 'Перевірка безпеки не пройдена. Оновіть сторінку.';
  end if;

  -- 4. User-based Rate Limit
  insert into public.comment_user_rate_limits(user_id, last_submitted_at)
  values (v_auth_user_id, now())
  on conflict (user_id) do update
  set last_submitted_at = now()
  where public.comment_user_rate_limits.last_submitted_at <= (now() - (v_cooldown_seconds || ' seconds')::interval);

  if not found then
    raise exception 'Зачекайте 20 секунд перед додаванням наступного відгуку';
  end if;

  -- 5. IP-based Rate Limit
  begin
    v_headers := current_setting('request.headers', true)::jsonb;
    v_client_ip := coalesce(
      nullif(trim(v_headers->>'cf-connecting-ip'), ''),
      'unknown'
    );
    if v_client_ip like '%,%' then
      v_client_ip := split_part(v_client_ip, ',', 1);
    end if;
  exception when others then
    v_client_ip := 'unknown';
  end;

  insert into public.comment_rate_limits(ip_address, last_submitted_at)
  values (v_client_ip, now())
  on conflict (ip_address) do update
  set last_submitted_at = now()
  where public.comment_rate_limits.last_submitted_at <= (now() - (v_cooldown_seconds || ' seconds')::interval);

  if not found then
    raise exception 'Зачекайте 20 секунд перед додаванням наступного відгуку';
  end if;

  -- 6. Insert comment
  insert into public.comments(page, author_name, author_email, content)
  values (
    coalesce(nullif(trim(p_page), ''), '/index.html'),
    v_auth_name,
    v_auth_email,
    trim(p_content)
  );

  return jsonb_build_object('success', true, 'message', 'Відгук опубліковано');
end;
$$;

revoke all on function public.submit_comment_secure(text, text, text, text) from public, anon;
grant execute on function public.submit_comment_secure(text, text, text, text) to authenticated;
