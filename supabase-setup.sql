create table if not exists public.admin_users (
  email text primary key check (email = lower(email)),
  role text not null check (role in ('editor','admin','super_admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.site_content (
  key text primary key,
  page text not null,
  value text not null,
  updated_by text not null,
  updated_at timestamptz not null default now()
);
create table if not exists public.news (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'general' check (category in ('general', 'important', 'it', 'sport')),
  body text not null,
  author_email text not null,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;
alter table public.site_content enable row level security;
alter table public.news enable row level security;

create or replace function public.is_site_admin() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admin_users where email = lower(coalesce(auth.jwt()->>'email','')) and role in ('admin','super_admin'))
$$;
revoke all on function public.is_site_admin() from public;
grant execute on function public.is_site_admin() to anon, authenticated;

create or replace function public.is_super_admin() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admin_users where email = lower(coalesce(auth.jwt()->>'email','')) and role = 'super_admin')
$$;
revoke all on function public.is_super_admin() from public;
grant execute on function public.is_super_admin() to anon, authenticated;

